package com.penvire.buildlogic.audit

import org.gradle.api.GradleException
import org.jboss.jandex.AnnotationInstance
import org.jboss.jandex.AnnotationTarget
import org.jboss.jandex.AnnotationValue
import org.jboss.jandex.ClassInfo
import org.jboss.jandex.DotName
import org.jboss.jandex.IndexView
import org.jboss.jandex.MethodInfo
import org.jboss.jandex.Type

private val AUDITED = DotName.createSimple("com.penvire.lab.audit.Audited")
private val AUDIT_IGNORED = DotName.createSimple("com.penvire.lab.audit.AuditIgnored")
private val ACTION = Regex("[a-z][a-z0-9-]*\\.[a-z][a-z0-9-]*\\.[a-z][a-z0-9-]*")

/** How an action records one field of its state. */
internal enum class Recording(val label: String) {
    VALUE("value"),
    PATH_ONLY("pathOnly"),
    IGNORED("ignored"),
}

/**
 * The audit manifest of a service (ADR 0006, ADR 0008): every `@Audited` method with its action,
 * the failures it records, and how it records each field of its state. Fields are classified with
 * the same rules as `StateChanges` in `libs/audit`, and declarations the library rejects at runtime
 * fail here too, so a broken declaration fails the build.
 */
internal class AuditManifest(private val classes: ClassFinder) {

    private class Action(
        val method: String,
        val action: String,
        val deniedOn: List<String>,
        val failedOn: List<String>,
        val state: String?,
        val fields: Map<String, Recording>,
    )

    private class Rules(val pathOnly: List<String>, val ignore: List<String>, val ignoreTypes: List<DotName>)

    /** The manifest as YAML, with actions sorted by method and fields by path. */
    fun render(index: IndexView): String {
        val actions = index.getAnnotations(AUDITED).map(::action).sortedBy { it.method }
        return buildString {
            append("# Generated by ./gradlew auditManifest from the @Audited methods (ADR 0006). Do not edit.\n")
            if (actions.isEmpty()) {
                append("actions: []\n")
                return@buildString
            }
            append("actions:\n")
            for (action in actions) {
                append("  - method: ${action.method}\n")
                append("    action: ${action.action}\n")
                list("deniedOn", action.deniedOn)
                list("failedOn", action.failedOn)
                if (action.state != null) {
                    append("    state: ${action.state}\n")
                    append("    fields:\n")
                    action.fields.forEach { (path, recording) -> append("      $path: ${recording.label}\n") }
                }
            }
        }
    }

    private fun StringBuilder.list(key: String, items: List<String>) {
        if (items.isEmpty()) {
            append("    $key: []\n")
        } else {
            append("    $key:\n")
            items.forEach { append("      - $it\n") }
        }
    }

    private fun action(audited: AnnotationInstance): Action {
        val target = audited.target()
        if (target.kind() != AnnotationTarget.Kind.METHOD) {
            throw GradleException("$target declares @Audited; declare it on each use case method")
        }
        val method = target.asMethod()
        val where = signature(method)

        val action = string(audited, "value")
        if (!ACTION.matches(action)) {
            throw GradleException("$where declares action '$action', which is not <service>.<resource>.<verb>")
        }

        val deniedOn = classNames(audited, "deniedOn")
        val failedOn = classNames(audited, "failedOn")
        deniedOn.intersect(failedOn.toSet()).firstOrNull()?.let {
            throw GradleException("$where lists $it as both denied and failed")
        }

        val rules = Rules(
            strings(audited, "pathOnly"),
            strings(audited, "ignore"),
            classNames(audited, "ignoreTypes").map(DotName::createSimple),
        )
        val stateType = value(audited, "state").asClass()
        if (stateType.kind() == Type.Kind.VOID) {
            if (rules.pathOnly.isNotEmpty() || rules.ignore.isNotEmpty()) {
                throw GradleException("$where lists audit paths but declares no state")
            }
            return Action(where, action, deniedOn, failedOn, null, emptyMap())
        }

        val state = record(stateType.name())
            ?: throw GradleException("$where declares ${stateType.name()} as state, which is no record")
        val known = paths(state)
        for (path in rules.pathOnly + rules.ignore) {
            if (path !in known) {
                throw GradleException("$where lists $path, which ${state.name()} has not")
            }
        }

        val fields = sortedMapOf<String, Recording>()
        if (ignoredType(state.name(), rules)) {
            state.recordComponents().forEach { fields[it.name()] = Recording.IGNORED }
        } else {
            classify("", state, rules, fields)
        }
        return Action(where, action, deniedOn, failedOn, state.name().toString(), fields)
    }

    /** Every path of a record, nested records and ignored fields included, like `StateChanges.paths`. */
    private fun paths(type: ClassInfo, prefix: String = ""): Set<String> {
        val paths = sortedSetOf<String>()
        for (component in type.recordComponents()) {
            val path = prefix + component.name()
            paths += path
            nestedRecord(component.type())?.let { paths += paths(it, "$path.") }
        }
        return paths
    }

    /** Ignoring first, then `pathOnly`, like `StateChanges.flatten` and `StateChanges.between`. */
    private fun classify(prefix: String, type: ClassInfo, rules: Rules, fields: MutableMap<String, Recording>) {
        for (component in type.recordComponents()) {
            val path = prefix + component.name()
            val fieldType = component.type()
            if (component.declaredAnnotation(AUDIT_IGNORED) != null ||
                ignoredType(fieldType.name(), rules) ||
                covers(rules.ignore, path)
            ) {
                fields[path] = Recording.IGNORED
                continue
            }
            val nested = nestedRecord(fieldType)
            if (nested != null) {
                classify("$path.", nested, rules, fields)
            } else {
                fields[path] = if (covers(rules.pathOnly, path)) Recording.PATH_ONLY else Recording.VALUE
            }
        }
    }

    /** The record a field walks into, or null for a value: primitives, arrays and other classes. */
    private fun nestedRecord(type: Type): ClassInfo? = when (type.kind()) {
        Type.Kind.CLASS, Type.Kind.PARAMETERIZED_TYPE -> record(type.name())
        else -> null
    }

    private fun record(name: DotName): ClassInfo? {
        val info = classes.find(name)
            ?: throw GradleException("$name is not on the runtime classpath, so its audited fields are unknown")
        return info.takeIf { it.isRecord }
    }

    /** Annotated `@AuditIgnored`, or a subtype of one of the action's `ignoreTypes`. */
    private fun ignoredType(name: DotName, rules: Rules): Boolean {
        if (classes.find(name)?.declaredAnnotation(AUDIT_IGNORED) != null) {
            return true
        }
        return rules.ignoreTypes.any { isSubtype(name, it, mutableSetOf()) }
    }

    private fun isSubtype(name: DotName, of: DotName, seen: MutableSet<DotName>): Boolean {
        if (name == of) {
            return true
        }
        if (!seen.add(name)) {
            return false
        }
        val info = classes.find(name) ?: return false
        return (listOfNotNull(info.superName()) + info.interfaceNames()).any { isSubtype(it, of, seen) }
    }

    /** Whether one of the paths is this path or a record above it. */
    private fun covers(paths: List<String>, path: String) =
        paths.any { path == it || path.startsWith("$it.") }

    /** The member's value, or the default declared on `Audited`. */
    private fun value(audited: AnnotationInstance, member: String): AnnotationValue =
        audited.value(member) ?: defaults().method(member).defaultValue()

    private fun defaults(): ClassInfo =
        classes.find(AUDITED) ?: throw GradleException("$AUDITED is not on the runtime classpath")

    private fun string(audited: AnnotationInstance, member: String): String = value(audited, member).asString()

    private fun strings(audited: AnnotationInstance, member: String): List<String> =
        value(audited, member).asStringArray().toList()

    private fun classNames(audited: AnnotationInstance, member: String): List<String> =
        value(audited, member).asClassArray().map { it.name().toString() }.sorted()

    private fun signature(method: MethodInfo): String =
        "${method.declaringClass().name()}#${method.name()}(${method.parameterTypes().joinToString(", ", transform = ::typeName)})"

    private fun typeName(type: Type): String =
        if (type.kind() == Type.Kind.ARRAY) typeName(type.asArrayType().component()) + "[]" else type.name().toString()
}
