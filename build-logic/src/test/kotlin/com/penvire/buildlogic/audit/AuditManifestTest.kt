package com.penvire.buildlogic.audit

import java.io.File
import java.io.StringWriter
import java.nio.file.Path
import javax.tools.ToolProvider
import org.gradle.api.GradleException
import org.jboss.jandex.Indexer
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.assertThrows
import org.junit.jupiter.api.io.TempDir

/**
 * The audit manifest of fixture use cases, compiled at test time against the real `Audited` and
 * `AuditIgnored` of `libs/audit`.
 */
class AuditManifestTest {

    @TempDir
    lateinit var dir: Path

    private val header =
        "# Generated by ./gradlew auditManifest from the @Audited methods (ADR 0006). Do not edit.\n"

    /** Mirrors the records of `AuditChangesTest` in `libs/audit`. */
    private val states = mapOf(
        "fixture/Widget.java" to """
            package fixture;
            import com.penvire.lab.audit.AuditIgnored;
            public record Widget(
                String name, int size, Colour colour, Dimensions dimensions, java.util.List<String> tags,
                String note, @AuditIgnored String secretHash, Owner owner, java.time.Instant updatedAt) {}
        """,
        "fixture/Colour.java" to "package fixture; public enum Colour { RED, BLUE }",
        "fixture/Dimensions.java" to "package fixture; public record Dimensions(int width, int height) {}",
        "fixture/Owner.java" to "package fixture; public record Owner(String email, Profile profile) {}",
        "fixture/Profile.java" to """
            package fixture;
            @com.penvire.lab.audit.AuditIgnored
            public record Profile(String displayName) {}
        """,
        "fixture/Gadget.java" to "package fixture; public interface Gadget {}",
    )

    @Test
    fun listsNoActionsForAServiceWithoutAuditedMethods() {
        assertEquals(header + "actions: []\n", manifest("public class Service { public void run() {} }"))
    }

    @Test
    fun listsEveryFieldOfTheStateWithHowItIsRecorded() {
        val manifest = manifest(
            """
            public class Service {
              @Audited(value = "widget.widget.update", state = Widget.class)
              public void update(java.util.UUID id, Widget before, Widget after) {}
            }
            """,
        )

        assertEquals(
            header +
                """
                actions:
                  - method: fixture.Service#update(java.util.UUID, fixture.Widget, fixture.Widget)
                    action: widget.widget.update
                    deniedOn:
                      - io.quarkus.security.ForbiddenException
                      - io.quarkus.security.UnauthorizedException
                    failedOn: []
                    state: fixture.Widget
                    fields:
                      colour: value
                      dimensions.height: value
                      dimensions.width: value
                      name: value
                      note: value
                      owner.email: value
                      owner.profile: ignored
                      secretHash: ignored
                      size: value
                      tags: value
                      updatedAt: value

                """.trimIndent(),
            manifest,
        )
    }

    @Test
    fun listsTheFailuresAnActionRecordsAndNoStateWithoutOne() {
        val manifest = manifest(
            """
            public class Service {
              @Audited(
                  value = "widget.key.rotate",
                  deniedOn = SecurityException.class,
                  failedOn = {IllegalStateException.class, java.io.UncheckedIOException.class})
              public void rotate() {}
            }
            """,
        )

        assertEquals(
            header +
                """
                actions:
                  - method: fixture.Service#rotate()
                    action: widget.key.rotate
                    deniedOn:
                      - java.lang.SecurityException
                    failedOn:
                      - java.io.UncheckedIOException
                      - java.lang.IllegalStateException

                """.trimIndent(),
            manifest,
        )
    }

    @Test
    fun marksPathOnlyFieldsAndEveryFieldUnderAPathOnlyRecord() {
        val fields = fields(
            """@Audited(value = "widget.widget.update", state = Widget.class, pathOnly = {"name", "dimensions"})""",
        )

        assertEquals("pathOnly", fields["name"])
        assertEquals("pathOnly", fields["dimensions.width"])
        assertEquals("pathOnly", fields["dimensions.height"])
        assertEquals("value", fields["size"])
    }

    @Test
    fun marksIgnoredPathsAndPrefersIgnoringOverPathOnly() {
        val fields = fields(
            """
            @Audited(
                value = "widget.widget.update",
                state = Widget.class,
                pathOnly = {"note", "owner"},
                ignore = {"note", "dimensions"})
            """,
        )

        assertEquals("ignored", fields["note"])
        assertEquals("ignored", fields["dimensions"])
        assertEquals(null, fields["dimensions.width"])
        assertEquals("pathOnly", fields["owner.email"])
        assertEquals("ignored", fields["owner.profile"])
    }

    @Test
    fun marksIgnoredTypesAndTheirSubtypesWherever() {
        val fields = fields(
            """
            @Audited(
                value = "widget.widget.update",
                state = Widget.class,
                ignoreTypes = {Dimensions.class, java.time.temporal.Temporal.class, java.util.Collection.class})
            """,
        )

        assertEquals("ignored", fields["dimensions"])
        assertEquals("ignored", fields["updatedAt"])
        assertEquals("ignored", fields["tags"])
        assertEquals("value", fields["name"])
    }

    @Test
    fun marksEveryFieldIgnoredWhenTheStateIsOfAnIgnoredType() {
        assertEquals(
            mapOf("displayName" to "ignored"),
            fields("""@Audited(value = "widget.profile.update", state = Profile.class)"""),
        )
    }

    @Test
    fun sortsActionsByMethod() {
        val manifest = manifest(
            """
            public class Service {
              @Audited("widget.widget.update") public void update() {}
              @Audited("widget.widget.create") public void create() {}
              @Audited("widget.widget.delete") public void delete(String id, int[] parts) {}
            }
            """,
        )

        val methods = manifest.lines().filter { it.startsWith("  - method: ") }.map { it.removePrefix("  - method: ") }
        assertEquals(
            listOf("fixture.Service#create()", "fixture.Service#delete(java.lang.String, int[])", "fixture.Service#update()"),
            methods,
        )
    }

    @Test
    fun rejectsAPathOnlyFieldTheStateDoesNotHave() {
        assertRejected(
            "owner.emial",
            """@Audited(value = "widget.widget.update", state = Widget.class, pathOnly = "owner.emial")""",
        )
    }

    @Test
    fun rejectsAnIgnoredFieldTheStateDoesNotHave() {
        assertRejected("nope", """@Audited(value = "widget.widget.update", state = Widget.class, ignore = "nope")""")
    }

    @Test
    fun rejectsPathsWithoutState() {
        assertRejected("declares no state", """@Audited(value = "widget.widget.update", ignore = "note")""")
    }

    @Test
    fun rejectsAStateThatIsNoRecord() {
        assertRejected("no record", """@Audited(value = "widget.gadget.update", state = Gadget.class)""")
    }

    @Test
    fun rejectsAFailureListedAsBothDeniedAndFailed() {
        assertRejected(
            "both denied and failed",
            """
            @Audited(
                value = "widget.widget.update",
                deniedOn = IllegalStateException.class,
                failedOn = IllegalStateException.class)
            """,
        )
    }

    @Test
    fun rejectsAMalformedAction() {
        assertRejected("not <service>.<resource>.<verb>", """@Audited("widget-update")""")
    }

    @Test
    fun rejectsAuditedOnAClass() {
        val failure = assertThrows<GradleException> {
            manifest("""@Audited("widget.widget.update") public class Service { public void update() {} }""")
        }
        assertTrue("declare it on each use case method" in failure.message.orEmpty(), failure.message)
    }

    private fun assertRejected(expected: String, annotation: String) {
        val failure = assertThrows<GradleException> { fields(annotation) }
        assertTrue(expected in failure.message.orEmpty(), failure.message)
    }

    /** The fields of one use case declared with the annotation, by path. */
    private fun fields(annotation: String): Map<String, String> =
        manifest("public class Service { $annotation public void update() {} }")
            .lines()
            .dropWhile { it != "    fields:" }
            .drop(1)
            .filter { it.isNotBlank() }
            .associate { line -> line.trim().split(": ").let { it[0] to it[1] } }

    private fun manifest(service: String): String {
        val classes = compile(
            states + ("fixture/Service.java" to "package fixture;\nimport com.penvire.lab.audit.*;\n$service"),
        )
        val indexer = Indexer()
        classes.walkTopDown()
            .filter { it.isFile && it.name.endsWith(".class") && it.path.contains("${File.separator}fixture${File.separator}Service") }
            .forEach { file -> file.inputStream().use { indexer.index(it) } }
        val classpath = System.getProperty("java.class.path").split(File.pathSeparator).map(::File)
        return ClassFinder(listOf(classes) + classpath).use { AuditManifest(it).render(indexer.complete()) }
    }

    private fun compile(sources: Map<String, String>): File {
        val src = dir.resolve("src").toFile()
        val files = sources.map { (path, source) ->
            File(src, path).apply {
                parentFile.mkdirs()
                writeText(source.trimIndent())
            }
        }
        val audit = File(System.getProperty("penvire.audit.sources"))
        val annotations = listOf(File(audit, "Audited.java"), File(audit, "AuditIgnored.java"))

        val out = dir.resolve("classes").toFile()
        val errors = StringWriter()
        val compiled = ToolProvider.getSystemJavaCompiler()
            .getTask(
                errors,
                null,
                null,
                listOf("-d", out.path, "-cp", System.getProperty("java.class.path"), "-proc:none"),
                null,
                ToolProvider.getSystemJavaCompiler()
                    .getStandardFileManager(null, null, null)
                    .getJavaFileObjectsFromFiles(files + annotations),
            )
            .call()
        assertTrue(compiled, errors.toString())
        return out
    }
}
