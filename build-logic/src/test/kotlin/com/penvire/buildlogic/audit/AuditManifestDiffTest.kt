package com.penvire.buildlogic.audit

import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Test

/** The pull request comment's section for one service, from two manifests. */
class AuditManifestDiffTest {

    private val update = ManifestAction(
        method = "fixture.Service#update(java.util.UUID)",
        action = "widget.widget.update",
        deniedOn = listOf("io.quarkus.security.ForbiddenException"),
        failedOn = emptyList(),
        state = "fixture.Widget",
        fields = mapOf("email" to "pathOnly", "name" to "value", "secretHash" to "ignored"),
    )

    private val rotate = ManifestAction(
        method = "fixture.Keys#rotate()",
        action = "widget.key.rotate",
        deniedOn = emptyList(),
        failedOn = listOf("java.lang.IllegalStateException"),
        state = null,
        fields = emptyMap(),
    )

    @Test
    fun readsTheManifestTheGeneratorWrites() {
        val yaml = """
            # Generated by ./gradlew auditManifest from the @Audited methods (ADR 0006). Do not edit.
            actions:
              - method: fixture.Keys#rotate()
                action: widget.key.rotate
                deniedOn: []
                failedOn:
                  - java.lang.IllegalStateException
              - method: fixture.Service#update(java.util.UUID)
                action: widget.widget.update
                deniedOn:
                  - io.quarkus.security.ForbiddenException
                failedOn: []
                state: fixture.Widget
                fields:
                  email: pathOnly
                  name: value
                  secretHash: ignored
        """.trimIndent()

        assertEquals(listOf(rotate, update), ManifestAction.parse(yaml))
    }

    @Test
    fun readsAManifestWithoutActions() {
        assertEquals(emptyList<ManifestAction>(), ManifestAction.parse("# header\nactions: []\n"))
    }

    @Test
    fun writesNothingWhenNothingChanged() {
        assertEquals("", AuditManifestDiff(listOf(update, rotate), listOf(rotate, update)).markdown("widget"))
    }

    @Test
    fun listsEveryValueOfANewActionFirst() {
        assertEquals(
            """
            ### widget

            **Now recorded with their values.** Check that none of them is personal data or a secret: a recorded value cannot be removed from the audit log.

            | Action | Field |
            | --- | --- |
            | `widget.widget.update` | `name` |

            **Added actions**

            - `widget.widget.update`: `fixture.Service#update(java.util.UUID)`


            """.trimIndent(),
            AuditManifestDiff(emptyList(), listOf(update)).markdown("widget"),
        )
    }

    @Test
    fun flagsAFieldThatStartsRecordingItsValue() {
        val changed = update.copy(fields = update.fields + ("email" to "value") + ("phone" to "value") - "secretHash")

        assertEquals(
            """
            ### widget

            **Now recorded with their values.** Check that none of them is personal data or a secret: a recorded value cannot be removed from the audit log.

            | Action | Field |
            | --- | --- |
            | `widget.widget.update` | `email` |
            | `widget.widget.update` | `phone` |

            **Changed actions**

            - `widget.widget.update` (`fixture.Service#update(java.util.UUID)`)
              - field `email`: `pathOnly` → `value`
              - field `phone` added: `value`
              - field `secretHash` removed


            """.trimIndent(),
            AuditManifestDiff(listOf(update), listOf(changed)).markdown("widget"),
        )
    }

    @Test
    fun listsRemovedActionsAndChangedDeclarationsWithoutValueWarning() {
        val changed = update.copy(
            action = "widget.widget.edit",
            deniedOn = listOf("fixture.WidgetLockedException"),
            failedOn = listOf("java.lang.IllegalStateException"),
            state = "fixture.WidgetV2",
            fields = update.fields + ("name" to "pathOnly"),
        )

        assertEquals(
            """
            ### widget

            **Removed actions**

            - `widget.key.rotate`: `fixture.Keys#rotate()`

            **Changed actions**

            - `widget.widget.edit` (`fixture.Service#update(java.util.UUID)`)
              - action: `widget.widget.update` → `widget.widget.edit`
              - deniedOn: added `fixture.WidgetLockedException`, removed `io.quarkus.security.ForbiddenException`
              - failedOn: added `java.lang.IllegalStateException`
              - state: `fixture.Widget` → `fixture.WidgetV2`
              - field `name`: `value` → `pathOnly`


            """.trimIndent(),
            AuditManifestDiff(listOf(update, rotate), listOf(changed)).markdown("widget"),
        )
    }
}
